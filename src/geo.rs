/// Walk every road and put a bridge across each stretch of water that is
/// short enough to span. Longer gaps simply break the road.
pub fn find_bridges(height: impl Fn(f32, f32) -> f32) -> Vec<BridgeSpan> {
    let mut out: Vec<BridgeSpan> = Vec::new();
    for r in 0..ROADS.len() {
        let pts = road_polyline(r);
        let wet: Vec<bool> = pts.iter().map(|p| height(p[0], p[1]) < SEA_LEVEL).collect();
        let mut i = 0;
        while i < pts.len() {
            if !wet[i] {
                i += 1;
                continue;
            }
            // Water run [i0, i1], merging runs split by tiny islets.
            let i0 = i;
            let mut i1 = i;
            let mut j = i;
            while j < pts.len() {
                if wet[j] {
                    i1 = j;
                } else if (j - i1) as f32 * ROAD_SAMPLE > 140.0 {
                    break;
                }
                j += 1;
            }
            i = i1 + 1;
            let pad = 3;
            if i0 < pad || i1 + pad >= pts.len() {
                continue; // road starts or ends in the water
            }
            let (a, b) = (pts[i0 - pad], pts[i1 + pad]);
            let len = dist(a, b);
            if len > BRIDGE_MAX_LENGTH || (i1 - i0 + 1) < 2 {
                continue;
            }
            // Roads that share a crossing share the bridge.
            let mid = [(a[0] + b[0]) * 0.5, (a[1] + b[1]) * 0.5];
            if out.iter().any(|o| dist([(o.a[0] + o.b[0]) * 0.5, (o.a[1] + o.b[1]) * 0.5], mid) < 600.0) {
                continue;
            }
            out.push(BridgeSpan { a, b, road: r });
        }
    }
    out
}

/// Name for a bridge: the nearest waterway and city.
pub fn bridge_name(span: &BridgeSpan) -> String {
    let mid = [(span.a[0] + span.b[0]) * 0.5, (span.a[1] + span.b[1]) * 0.5];
    let mut water = ("Sea", f32::MAX);
    for w in WATERWAYS {
        for s in world_pts(w.pts).windows(2) {
            let d = seg_dist(mid, s[0], s[1]).0;
            if d < water.1 {
                water = (w.name, d);
            }
        }
    }
    let water = if water.1 < 1_500.0 { water.0 } else { "Sea" };
    let city = CITIES
        .iter()
        .min_by(|a, b| dist(geo_ll(a.1), mid).total_cmp(&dist(geo_ll(b.1), mid)))
        .map(|c| c.0)
        .unwrap_or("?");
    format!("{water} bridge near {city}")
}

// ---------------------------------------------------------------------------
// Noise (shared with heightgen)
// ---------------------------------------------------------------------------

pub fn hash(ix: i32, iz: i32, seed: u32) -> f32 {
    let mut h = (ix as u32).wrapping_mul(0x8da6_b343) ^ (iz as u32).wrapping_mul(0xd816_3841) ^ seed.wrapping_mul(0xcb1a_b31f);
    h ^= h >> 13;
    h = h.wrapping_mul(0x5bd1_e995);
    h ^= h >> 15;
    (h & 0x00ff_ffff) as f32 / 16_777_216.0
}

fn smooth(t: f32) -> f32 {
    t * t * (3.0 - 2.0 * t)
}

pub fn smoothstep(e0: f32, e1: f32, x: f32) -> f32 {
    smooth(((x - e0) / (e1 - e0)).clamp(0.0, 1.0))
}

pub fn lerp(a: f32, b: f32, t: f32) -> f32 {
    a + (b - a) * t
}

pub fn value_noise(x: f32, z: f32, seed: u32) -> f32 {
    let (ix, iz) = (x.floor() as i32, z.floor() as i32);
    let (fx, fz) = (smooth(x - x.floor()), smooth(z - z.floor()));
    let a = hash(ix, iz, seed);
    let b = hash(ix + 1, iz, seed);
    let c = hash(ix, iz + 1, seed);
    let d = hash(ix + 1, iz + 1, seed);
    lerp(lerp(a, b, fx), lerp(c, d, fx), fz)
}

pub fn fbm(x: f32, z: f32, octaves: u32, seed: u32) -> f32 {
    let (mut sum, mut amp, mut freq, mut norm) = (0.0, 0.5, 1.0, 0.0);
    for o in 0..octaves {
        sum += amp * value_noise(x * freq, z * freq, seed + o * 17);
        norm += amp;
        amp *= 0.5;
        freq *= 2.03;
    }
    sum / norm
}

