pub fn world_pts(pts: &[LonLat]) -> Vec<[f32; 2]> {
    pts.iter().map(|p| geo_ll(*p)).collect()
}

/// Resample a polyline every `step` meters and add a gentle meander
/// (`amp` meters) that tapers to zero at both ends, so the endpoints stay
/// exact. Deterministic: the game and the generator agree on every point.
pub fn densify(pts: &[[f32; 2]], step: f32, amp: f32, seed: u32) -> Vec<[f32; 2]> {
    let mut out = Vec::new();
    let mut s0 = 0.0;
    let phase = hash(seed as i32, 7, 3) * 6.28;
    for w in pts.windows(2) {
        let (a, b) = (w[0], w[1]);
        let len = dist(a, b);
        let n = (len / step).ceil().max(1.0) as usize;
        let dir = [(b[0] - a[0]) / len.max(1e-3), (b[1] - a[1]) / len.max(1e-3)];
        let perp = [-dir[1], dir[0]];
        for i in 0..n {
            let t = i as f32 / n as f32;
            let s = s0 + len * t;
            // Taper over the first/last 1.5 km of every leg, so cities and
            // corners are hit exactly.
            let taper = smoothstep(0.0, 1_500.0, (len * t).min(len * (1.0 - t)));
            let m = amp * taper * ((s / 1_700.0 + phase).sin() * 0.7 + (s / 610.0 + phase * 1.7).sin() * 0.3);
            out.push([a[0] + (b[0] - a[0]) * t + perp[0] * m, a[1] + (b[1] - a[1]) * t + perp[1] * m]);
        }
        s0 += len;
    }
    if let Some(last) = pts.last() {
        out.push(*last);
    }
    out
}

pub fn road_polyline(i: usize) -> Vec<[f32; 2]> {
    densify(&world_pts(ROADS[i].pts), ROAD_SAMPLE, ROAD_MEANDER, 100 + i as u32)
}

pub fn waterway_polyline(i: usize) -> Vec<[f32; 2]> {
    let w = &WATERWAYS[i];
    let amp = if w.strait { 0.0 } else { RIVER_MEANDER };
    densify(&world_pts(w.pts), 60.0, amp, 200 + i as u32)
}

pub fn dist(a: [f32; 2], b: [f32; 2]) -> f32 {
    ((a[0] - b[0]).powi(2) + (a[1] - b[1]).powi(2)).sqrt()
}

/// Distance from p to segment ab, and the parameter t of the closest point.
pub fn seg_dist(p: [f32; 2], a: [f32; 2], b: [f32; 2]) -> (f32, f32) {
    let ab = [b[0] - a[0], b[1] - a[1]];
    let l2 = ab[0] * ab[0] + ab[1] * ab[1];
    let t = if l2 < 1e-6 { 0.0 } else { (((p[0] - a[0]) * ab[0] + (p[1] - a[1]) * ab[1]) / l2).clamp(0.0, 1.0) };
    (dist(p, [a[0] + ab[0] * t, a[1] + ab[1] * t]), t)
}

