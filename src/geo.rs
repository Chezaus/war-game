/// Deserts: (lon, lat, half extent lon, half extent lat).
const DESERTS: &[(f32, f32, f32, f32)] = &[
    (8.0, 23.0, 26.0, 8.5),     // Sahara
    (45.0, 23.0, 11.0, 7.0),    // Arabia
    (60.0, 40.0, 9.0, 5.0),     // Karakum
    (95.0, 42.0, 18.0, 5.5),    // Gobi, Taklamakan
    (131.0, -25.0, 13.0, 7.0),  // Australian outback
    (-112.0, 33.0, 6.0, 4.0),   // Sonoran, Mojave
    (-70.0, -23.0, 2.0, 7.0),   // Atacama
    (20.0, -24.0, 5.0, 4.0),    // Kalahari
    (68.0, 27.0, 5.0, 3.0),     // Thar
];

/// 0 = none, 1 = full desert.
pub fn desert(lon: f32, lat: f32) -> f32 {
    let mut d: f32 = 0.0;
    let ragged = (fbm(lon / 5.0, lat / 5.0, 3, 31) - 0.5) * 1.1;
    for &(cx, cy, rx, ry) in DESERTS {
        let u = ((lon - cx) / rx).powi(2) + ((lat - cy) / ry).powi(2) + ragged;
        d = d.max(1.0 - smoothstep(0.55, 1.0, u));
    }
    d
}

/// Snow and ice from latitude (and altitude).
pub fn snow(lat: f32, h: f32) -> f32 {
    let polar = smoothstep(70.0, 76.0, lat).max(smoothstep(-64.0, -68.0, lat));
    // The snow line drops towards the poles.
    let alpine = smoothstep(800.0, 1_050.0, h + (lat.abs() - 45.0).max(0.0) * 10.0);
    polar.max(alpine)
}

/// How much forest the climate allows (0..1).
pub fn forest_climate(lat: f32, lon: f32) -> f32 {
    let a = lat.abs();
    let temperate = smoothstep(40.0, 46.0, a) * (1.0 - smoothstep(64.0, 69.0, a));
    let mediterranean = smoothstep(33.0, 38.0, a) * (1.0 - smoothstep(40.0, 46.0, a)) * 0.45;
    let tropical = 1.0 - smoothstep(10.0, 18.0, a);
    let subtropical = smoothstep(10.0, 18.0, a) * (1.0 - smoothstep(28.0, 33.0, a)) * 0.35;
    (temperate + mediterranean + tropical + subtropical).min(1.0) * (1.0 - desert(lon, lat))
}

/// Forest density in [0, 1] at world (x, z) with terrain height `h`.
/// Above FOREST_THRESHOLD a place counts as forest (trees, cover).
pub fn forest_density(x: f32, z: f32, h: f32) -> f32 {
    if h < 2.0 || h > 1_100.0 {
        return 0.0;
    }
    let (lon, lat) = lonlat(x, z);
    let n = fbm(x / 3_200.0, z / 3_200.0, 4, 21);
    let patch = smoothstep(0.40, 0.60, n);
    patch * forest_climate(lat, lon) * (1.0 - smoothstep(650.0, 950.0, h))
}

